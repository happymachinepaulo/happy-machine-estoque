-- 018 · Mini estoques por pessoa (Bruno, Matheus...) e destino/origem de cada saída e entrada.
-- Seguro para rodar mais de uma vez. Não altera quantidades existentes.
--
-- Como funciona:
--  * products.quantity continua sendo o estoque central (o que está guardado).
--  * holder_stock guarda o que está com cada pessoa.
--  * Saída: vai para um lugar/motivo (destination) OU para o estoque de uma pessoa (holder_id).
--  * Entrada: vem de um lugar/motivo OU devolvida do estoque de uma pessoa.
--  * Baixa ("consumo"): a pessoa usou a peça num lugar; sai só do estoque da pessoa.
begin;

create table if not exists public.holders (
 id bigint generated by default as identity primary key,
 name text not null check(length(trim(name)) between 1 and 80),
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create unique index if not exists holders_name_uidx on public.holders (lower(trim(name)));

create table if not exists public.holder_stock (
 holder_id bigint not null references public.holders(id) on delete cascade,
 product_id bigint not null references public.products(id) on delete cascade,
 quantity integer not null default 0 check(quantity >= 0),
 updated_at timestamptz not null default now(),
 primary key (holder_id, product_id)
);
create index if not exists holder_stock_product_idx on public.holder_stock (product_id);

alter table public.movements add column if not exists holder_id bigint references public.holders(id) on delete set null;
alter table public.movements add column if not exists destination text not null default '';
create index if not exists movements_holder_idx on public.movements (holder_id, id desc);
alter table public.movements drop constraint if exists movements_kind_check;
alter table public.movements add constraint movements_kind_check check (kind in ('entrada','saida','ajuste','cadastro','consumo'));

alter table public.holders enable row level security;
alter table public.holder_stock enable row level security;
drop policy if exists stock_read on public.holders;
drop policy if exists require_mfa on public.holders;
drop policy if exists stock_read on public.holder_stock;
drop policy if exists require_mfa on public.holder_stock;
create policy stock_read on public.holders for select to authenticated using ((select public.stock_access(false)));
create policy require_mfa on public.holders as restrictive for all to authenticated using ((select public.stock_access(false))) with check ((select public.stock_access(false)));
create policy stock_read on public.holder_stock for select to authenticated using ((select public.stock_access(false)));
create policy require_mfa on public.holder_stock as restrictive for all to authenticated using ((select public.stock_access(false))) with check ((select public.stock_access(false)));
revoke all on public.holders, public.holder_stock from public, anon, authenticated;
grant select on public.holders, public.holder_stock to authenticated;
grant all on public.holders, public.holder_stock to service_role;
grant usage, select on all sequences in schema public to service_role;

insert into public.holders(name) values ('Bruno'), ('Matheus') on conflict do nothing;

-- stock_command: mesmas ações de antes + destino/pessoa nas movimentações + comandos das pessoas.
create or replace function public.stock_command(command text,pid bigint default null,payload jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.products; ph public.photos; h public.holders; old jsonb; result jsonb; target_id bigint;
 before_q integer; after_q integer; delta_q integer; k text; status text; hid bigint; dest text; hq integer;
begin
 if not public.stock_access(false) then raise exception 'Acesso exige conta ativa e 2FA' using errcode='42501'; end if;
 if command='holder_create' then
  if length(trim(coalesce(payload->>'name',''))) not between 1 and 80 then raise exception 'Informe o nome da pessoa'; end if;
  if exists(select 1 from public.holders where lower(trim(name))=lower(trim(payload->>'name'))) then raise exception 'Já existe uma pessoa com esse nome'; end if;
  insert into public.holders(name) values(trim(payload->>'name')) returning * into h;
  insert into public.audit_log(action,after_data,actor_id) values('holder_create',to_jsonb(h)::text,auth.uid());
  return jsonb_build_object('ok',true,'id',h.id);
 elsif command='holder_update' then
  select * into h from public.holders where id=pid for update;
  if not found then raise exception 'Pessoa não encontrada'; end if;
  if payload ? 'name' then
   if length(trim(coalesce(payload->>'name',''))) not between 1 and 80 then raise exception 'Informe o nome da pessoa'; end if;
   if exists(select 1 from public.holders where id<>pid and lower(trim(name))=lower(trim(payload->>'name'))) then raise exception 'Já existe uma pessoa com esse nome'; end if;
  end if;
  if coalesce((payload->>'active')::boolean,true)=false and exists(select 1 from public.holder_stock where holder_id=pid and quantity>0) then
   raise exception 'Esta pessoa ainda tem peças. Devolva ou dê baixa antes de arquivar.';
  end if;
  update public.holders set name=coalesce(trim(payload->>'name'),name),active=coalesce((payload->>'active')::boolean,active) where id=pid;
  insert into public.audit_log(action,before_data,after_data,actor_id) values('holder_update',to_jsonb(h)::text,payload::text,auth.uid());
  return jsonb_build_object('ok',true);
 elsif command='create' then
  if length(trim(coalesce(payload->>'name','')))=0 then raise exception 'Informe o nome da peça'; end if;
  if payload ? 'existing_photo_id' then
   select * into ph from public.photos where id=(payload->>'existing_photo_id')::bigint for update;
   if not found or ph.review_status='confirmada' then raise exception 'Foto indisponível para cadastro'; end if;
  end if;
  insert into public.products(name,category,quantity,min_quantity,notes,source_text)
  values(trim(payload->>'name'),coalesce(payload->>'category',''),coalesce((payload->>'quantity')::integer,0),coalesce((payload->>'min_quantity')::integer,0),coalesce(payload->>'notes',''),'Cadastro online') returning * into p;
  insert into public.movements(product_id,kind,amount,before_qty,after_qty,note,actor_id) values(p.id,'cadastro',p.quantity,0,p.quantity,'Cadastro do item',auth.uid());
  if ph.id is not null then
   update public.photos set product_id=p.id,review_status='confirmada',is_primary=1 where id=ph.id;
   if ph.product_id is not null then
    update public.photos set is_primary=1 where id=(select id from public.photos where product_id=ph.product_id and review_status='confirmada' order by is_primary desc,id limit 1);
   end if;
  end if;
  result=jsonb_build_object('ok',true,'id',p.id);
 elsif command='review_photo' then
  select * into ph from public.photos where id=pid for update;
  if not found then raise exception 'Foto não encontrada'; end if;
  old=to_jsonb(ph); status=payload->>'status';
  if status not in ('confirmada','pendente','oculta') or status is null then raise exception 'Situação inválida'; end if;
  target_id=ph.product_id;
  if status='confirmada' then
   target_id=(payload->>'product_id')::bigint;
   if target_id is null or not exists(select 1 from public.products where id=target_id) then raise exception 'Selecione uma peça existente'; end if;
   perform 1 from public.products where id=target_id for update;
   if coalesce((payload->>'primary')::boolean,true) then update public.photos set is_primary=0 where product_id=target_id; end if;
  end if;
  update public.photos set product_id=target_id,review_status=status,is_primary=case when status='confirmada' and coalesce((payload->>'primary')::boolean,true) then 1 else 0 end,review_note=coalesce(payload->>'note',review_note) where id=pid;
  if ph.product_id is not null and not exists(select 1 from public.photos where product_id=ph.product_id and review_status='confirmada' and is_primary=1) then
   update public.photos set is_primary=1 where id=(select id from public.photos where product_id=ph.product_id and review_status='confirmada' order by id limit 1);
  end if;
  p.id=target_id; result=jsonb_build_object('ok',true);
 else
  select * into p from public.products where id=pid for update;
  if not found then raise exception 'Produto não encontrado'; end if;
  old=to_jsonb(p);
  hid=nullif(payload->>'holder_id','')::bigint; dest=left(trim(coalesce(payload->>'destination','')),120);
  if hid is not null then
   select * into h from public.holders where id=hid;
   if not found or not h.active then raise exception 'Pessoa não encontrada'; end if;
  end if;
  if command='movement' then
   before_q=p.quantity; k=payload->>'kind';
   if k='ajuste' then after_q=(payload->>'new_quantity')::integer; delta_q=after_q-before_q; hid=null;
   elsif k in ('entrada','saida') then
    delta_q=(payload->>'amount')::integer;
    if delta_q is null or delta_q<=0 then raise exception 'Informe uma quantidade maior que zero'; end if;
    if hid is null and dest='' then raise exception 'Informe para onde foi ou de onde veio'; end if;
    if hid is not null then
     insert into public.holder_stock(holder_id,product_id,quantity) values(hid,pid,0) on conflict do nothing;
     select quantity into hq from public.holder_stock where holder_id=hid and product_id=pid for update;
     if k='entrada' and hq<delta_q then raise exception '% tem só % desta peça', h.name, hq; end if;
     update public.holder_stock set quantity=quantity+case when k='saida' then delta_q else -delta_q end,updated_at=now() where holder_id=hid and product_id=pid;
     dest=h.name;
    end if;
    if k='saida' then delta_q=-delta_q; end if;
    after_q=before_q+delta_q;
   else raise exception 'Tipo de movimentação inválido'; end if;
   if after_q is null or after_q<0 then raise exception 'Saída maior que o estoque atual ou contagem inválida'; end if;
   update public.products set quantity=after_q,updated_at=now() where id=pid;
   insert into public.movements(product_id,kind,amount,before_qty,after_qty,note,actor_id,holder_id,destination) values(pid,k,delta_q,before_q,after_q,coalesce(payload->>'note',''),auth.uid(),hid,dest);
   result=jsonb_build_object('ok',true,'before',before_q,'after',after_q);
  elsif command='holder_consume' then
   -- a pessoa usou a peça: sai só do estoque dela; before/after são do estoque da pessoa
   delta_q=(payload->>'amount')::integer;
   if hid is null then raise exception 'Escolha a pessoa'; end if;
   if delta_q is null or delta_q<=0 then raise exception 'Informe uma quantidade maior que zero'; end if;
   if dest='' then raise exception 'Informe onde a peça foi usada'; end if;
   select quantity into hq from public.holder_stock where holder_id=hid and product_id=pid for update;
   if hq is null or hq<delta_q then raise exception '% tem só % desta peça', h.name, coalesce(hq,0); end if;
   update public.holder_stock set quantity=quantity-delta_q,updated_at=now() where holder_id=hid and product_id=pid;
   insert into public.movements(product_id,kind,amount,before_qty,after_qty,note,actor_id,holder_id,destination) values(pid,'consumo',-delta_q,hq,hq-delta_q,coalesce(payload->>'note',''),auth.uid(),hid,dest);
   result=jsonb_build_object('ok',true,'before',hq,'after',hq-delta_q);
  elsif command='update' then
   update public.products set name=trim(payload->>'name'),category=coalesce(payload->>'category',''),min_quantity=coalesce((payload->>'min_quantity')::integer,0),notes=coalesce(payload->>'notes',''),updated_at=now() where id=pid;
   result=jsonb_build_object('ok',true);
  elsif command='confirm' then
   update public.products set review_status='confirmado',updated_at=now() where id=pid;
   result=jsonb_build_object('ok',true);
  elsif command='delete' then
   if exists(select 1 from public.holder_stock where product_id=pid and quantity>0) then raise exception 'Esta peça ainda está com alguém. Devolva antes de excluir.'; end if;
   update public.photos set product_id=null,is_primary=0,review_status='pendente' where product_id=pid;
   delete from public.products where id=pid;
   result=jsonb_build_object('ok',true);
  else raise exception 'Ação inválida'; end if;
 end if;
 if command in ('create','update') and payload ? 'photo' then
  update public.photos set is_primary=0 where product_id=p.id;
  insert into public.photos(product_id,filename,mime,storage_path,is_primary) values(p.id,payload->'photo'->>'filename',payload->'photo'->>'mime',payload->'photo'->>'storage_path',1);
 end if;
 insert into public.audit_log(product_id,action,before_data,after_data,actor_id) values(p.id,command,coalesce(old::text,''),payload::text,auth.uid());
 return result;
end $$;
revoke all on function public.stock_command(text,bigint,jsonb) from public;
grant execute on function public.stock_command(text,bigint,jsonb) to authenticated;

insert into public.migration_runs(id, summary) values ('estoque-pessoas-20261103', '{"feature":"holders+holder_stock+destination","stock_quantity_changes":0}'::jsonb) on conflict (id) do nothing;
notify pgrst, 'reload schema';
commit;
