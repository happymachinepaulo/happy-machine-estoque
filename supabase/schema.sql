create table if not exists public.repairs (
 id bigint generated by default as identity primary key,
 name text not null check(length(trim(name)) between 1 and 160),
 category text not null default '' check(length(category)<=100),
 quantity integer not null check(quantity between 1 and 1000000),
 defect text not null check(length(trim(defect)) between 1 and 2000),
 notes text not null default '' check(length(notes)<=4000),
 status text not null default 'aguardando' check(status in ('aguardando','em_conserto','consertada','sem_conserto')),
 photo_path text, photo_mime text,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 actor_id uuid references auth.users(id) on delete set null, archived_at timestamptz
);
