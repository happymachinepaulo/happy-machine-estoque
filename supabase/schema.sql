create or replace function public.repair_command(command text,pid bigint default null,payload jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare old public.repairs; item public.repairs; n text; d text; s text; q integer;
begin
 if not public.stock_access(false) then raise exception 'Confirme o código de acesso'; end if;
 if command not in ('create','update','archive') then raise exception 'Operação inválida'; end if;
 if command<>'create' then
  select * into old from public.repairs where id=pid and archived_at is null for update;
  if not found then raise exception 'Peça para conserto não encontrada'; end if;
  if payload->>'updated_at' is null or (payload->>'updated_at')::timestamptz<>old.updated_at then
   raise exception 'Esta peça foi atualizada por outra pessoa. Recarregue antes de salvar.';
  end if;
 end if;
 if command='archive' then
  update public.repairs set archived_at=now(),updated_at=now() where id=pid returning * into item;
 else
  n=trim(coalesce(payload->>'name',''));d=trim(coalesce(payload->>'defect',''));s=coalesce(payload->>'status','aguardando');
  if length(n) not between 1 and 160 or length(d) not between 1 and 2000 then raise exception 'Informe nome e defeito'; end if;
  if coalesce(payload->>'quantity','') !~ '^[0-9]+$' then raise exception 'Quantidade inválida'; end if;
  q=(payload->>'quantity')::integer;
  if q not between 1 and 1000000 or s not in ('aguardando','em_conserto','consertada','sem_conserto') then raise exception 'Quantidade ou situação inválida'; end if;
  if payload ? 'photo_path' and coalesce(payload->>'photo_path','') !~ '^repairs/[a-f0-9]{48}\.(jpg|png|webp|gif)$' then raise exception 'Foto inválida'; end if;
  if command='create' then
   insert into public.repairs(name,category,quantity,defect,notes,status,photo_path,photo_mime,actor_id)
   values(n,coalesce(payload->>'category',''),q,d,coalesce(payload->>'notes',''),s,payload->>'photo_path',payload->>'photo_mime',auth.uid()) returning * into item;
  else
   update public.repairs set name=n,category=coalesce(payload->>'category',''),quantity=q,defect=d,
    notes=coalesce(payload->>'notes',''),status=s,updated_at=now(),
    photo_path=case when payload ? 'photo_path' then payload->>'photo_path' else old.photo_path end,
    photo_mime=case when payload ? 'photo_path' then payload->>'photo_mime' else old.photo_mime end
   where id=pid returning * into item;
  end if;
 end if;
 insert into public.audit_log(action,before_data,after_data,actor_id)
 values('repair_'||command,coalesce(old::text,''),item::text,auth.uid());
 return to_jsonb(item);
end $$;
revoke all on function public.repair_command(text,bigint,jsonb) from public,anon;
grant execute on function public.repair_command(text,bigint,jsonb) to authenticated;
