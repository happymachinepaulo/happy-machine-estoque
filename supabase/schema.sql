-- Every mutation is atomic, with a row lock for quantities and an audit trail.
create function public.stock_command(command text,pid bigint default null,payload jsonb default '{}'::jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare p public.products; ph public.photos; old jsonb; result jsonb; target_id bigint;
 before_q integer; after_q integer; delta_q integer; k text; status text;
begin
 if not public.stock_access(false) then raise exception 'Acesso exige conta ativa e 2FA' using errcode='42501'; end if;
 if command='create' then
  if length(trim(coalesce(payload->>'name','')))=0 then raise exception 'Informe o nome da peça'; end if;
  if payload ? 'existing_photo_id' then
   select * into ph from public.photos where id=(payload->>'existing_photo_id')::bigint for update;
   if not found or ph.review_status='confirmada' then raise exception 'Foto indisponível para cadastro'; end if;
  end if;
  insert into public.products(name,category,quantity,min_quantity,notes,source_text)
  values(trim(payload->>'name'),coalesce(payload->>'category',''),coalesce((payload->>'quantity')::integer,0),coalesce((payload->>'min_quantity')::integer,0),coalesce(payload->>'notes',''),'Cadastro online') returning * into p;
  insert into public.movements(product_id,kind,amount,before_qty,after_qty,note,actor_id) values(p.id,'cadastro',p.quantity,0,p.quantity,'Cadastro do item',auth.uid());
  if ph.id is not null then
   update public.photos set product_id=p.id,review_status='confirmada',is_primary=1 where id=ph.id;
   if ph.product_id is not null then
    update public.photos set is_primary=1 where id=(select id from public.photos where product_id=ph.product_id and review_status='confirmada' order by is_primary desc,id limit 1);
   end if;
  end if;
  result=jsonb_build_object('ok',true,'id',p.id);
 elsif command='review_photo' then
  select * into ph from public.photos where id=pid for update;
  if not found then raise exception 'Foto não encontrada'; end if;
  old=to_jsonb(ph); status=payload->>'status';
  if status not in ('confirmada','pendente','oculta') or status is null then raise exception 'Situação inválida'; end if;
  target_id=ph.product_id;
  if status='confirmada' then
   target_id=(payload->>'product_id')::bigint;
   if target_id is null or not exists(select 1 from public.products where id=target_id) then raise exception 'Selecione uma peça existente'; end if;
   perform 1 from public.products where id=target_id for update;
   if coalesce((payload->>'primary')::boolean,true) then update public.photos set is_primary=0 where product_id=target_id; end if;
  end if;
  update public.photos set product_id=target_id,review_status=status,is_primary=case when status='confirmada' and coalesce((payload->>'primary')::boolean,true) then 1 else 0 end,review_note=coalesce(payload->>'note',review_note) where id=pid;
  if ph.product_id is not null and not exists(select 1 from public.photos where product_id=ph.product_id and review_status='confirmada' and is_primary=1) then
   update public.photos set is_primary=1 where id=(select id from public.photos where product_id=ph.product_id and review_status='confirmada' order by id limit 1);
  end if;
  p.id=target_id; result=jsonb_build_object('ok',true);
 else
  select * into p from public.products where id=pid for update;
  if not found then raise exception 'Produto não encontrado'; end if;
  old=to_jsonb(p);
  if command='movement' then
   before_q=p.quantity; k=payload->>'kind';
   if k='ajuste' then after_q=(payload->>'new_quantity')::integer; delta_q=after_q-before_q;
   elsif k in ('entrada','saida') then
    delta_q=(payload->>'amount')::integer;
    if delta_q is null or delta_q<=0 then raise exception 'Informe uma quantidade maior que zero'; end if;
    if k='saida' then delta_q=-delta_q; end if;
    after_q=before_q+delta_q;
   else raise exception 'Tipo de movimentação inválido'; end if;
   if after_q is null or after_q<0 then raise exception 'Saída maior que o estoque atual ou contagem inválida'; end if;
   update public.products set quantity=after_q,updated_at=now() where id=pid;
   insert into public.movements(product_id,kind,amount,before_qty,after_qty,note,actor_id) values(pid,k,delta_q,before_q,after_q,coalesce(payload->>'note',''),auth.uid());
   result=jsonb_build_object('ok',true,'before',before_q,'after',after_q);
  elsif command='update' then
   update public.products set name=trim(payload->>'name'),category=coalesce(payload->>'category',''),min_quantity=coalesce((payload->>'min_quantity')::integer,0),notes=coalesce(payload->>'notes',''),updated_at=now() where id=pid;
   result=jsonb_build_object('ok',true);
  elsif command='confirm' then
   update public.products set review_status='confirmado',updated_at=now() where id=pid;
   result=jsonb_build_object('ok',true);
  elsif command='delete' then
   update public.photos set product_id=null,is_primary=0,review_status='pendente' where product_id=pid;
   delete from public.products where id=pid;
   result=jsonb_build_object('ok',true);
  else raise exception 'Ação inválida'; end if;
 end if;
 -- Attach uploaded photos inside the same transaction as create/update.
 if command in ('create','update') and payload ? 'photo' then
  update public.photos set is_primary=0 where product_id=p.id;
  insert into public.photos(product_id,filename,mime,storage_path,is_primary) values(p.id,payload->'photo'->>'filename',payload->'photo'->>'mime',payload->'photo'->>'storage_path',1);
 end if;
 insert into public.audit_log(product_id,action,before_data,after_data,actor_id) values(p.id,command,coalesce(old::text,''),payload::text,auth.uid());
 return result;
end $$;
revoke all on function public.stock_command(text,bigint,jsonb) from public;
grant execute on function public.stock_command(text,bigint,jsonb) to authenticated;

create function public.reset_stock_sequences() returns void language plpgsql security definer set search_path='' as $$
begin
 perform pg_catalog.setval(pg_catalog.pg_get_serial_sequence('public.products','id'),coalesce((select max(id) from public.products),0)+1,false);
 perform pg_catalog.setval(pg_catalog.pg_get_serial_sequence('public.photos','id'),coalesce((select max(id) from public.photos),0)+1,false);
 perform pg_catalog.setval(pg_catalog.pg_get_serial_sequence('public.movements','id'),coalesce((select max(id) from public.movements),0)+1,false);
 perform pg_catalog.setval(pg_catalog.pg_get_serial_sequence('public.audit_log','id'),coalesce((select max(id) from public.audit_log),0)+1,false);
end $$;
revoke all on function public.reset_stock_sequences() from public,anon,authenticated;
grant execute on function public.reset_stock_sequences() to service_role;

